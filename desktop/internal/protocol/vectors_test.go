// The vectors in protocol/testvectors/v1.json are shared with the Android
// implementation. Regenerate them with:
//
//	go test ./internal/protocol -run TestVectors -update
//
// and review the diff: a change to an existing vector is a wire break.
var update = flag.Bool("update", false, "rewrite protocol/testvectors/v1.json")

var vectorsPath = filepath.Join("..", "..", "..", "protocol", "testvectors", "v1.json")

type axisVector struct {
	Value float32 `json:"value"`
	Wire  int16   `json:"wire"`
}

type triggerVector struct {
	Value float32 `json:"value"`
	Wire  uint8   `json:"wire"`
}

type seqVector struct {
	A     uint16 `json:"a"`
	B     uint16 `json:"b"`
	Newer bool   `json:"newer"`
}

type stateVector struct {
	Name    string `json:"name"`
	Seq     uint16 `json:"seq"`
	Buttons uint16 `json:"buttons"`
	DPad    uint8  `json:"dpad"`
	Flags   uint8  `json:"flags"`
	LX      int16  `json:"lx"`
	LY      int16  `json:"ly"`
	RX      int16  `json:"rx"`
	RY      int16  `json:"ry"`
	LT      uint8  `json:"lt"`
	RT      uint8  `json:"rt"`
	Hex     string `json:"hex"`
}

type invalidVector struct {
	Name  string `json:"name"`
	Hex   string `json:"hex"`
	Error string `json:"error"`
}

type pairingVector struct {
	SecretHex  string `json:"secretHex"`
	Code       string `json:"code"`
	PairKeyHex string `json:"pairKeyHex"`
}

type handshakeVector struct {
	DeviceID       uint64 `json:"deviceId"`
	DeviceName     string `json:"deviceName"`
	ClientNonceHex string `json:"clientNonceHex"`
	ServerNonceHex string `json:"serverNonceHex"`
	SessionID      uint32 `json:"sessionId"`
	HelloHex       string `json:"helloHex"`
	WelcomeHex     string `json:"welcomeHex"`
	C2SKeyHex      string `json:"c2sKeyHex"`
	S2CKeyHex      string `json:"s2cKeyHex"`
}

type sessionVector struct {
	Name      string `json:"name"`
	Direction string `json:"direction"` // "c2s" or "s2c"
	Ext       uint64 `json:"ext"`
	Hex       string `json:"hex"` // full datagram including tag
}

type vectorFile struct {
	Comment   string          `json:"comment"`
	Version   uint8           `json:"version"`
	Axis      []axisVector    `json:"axis"`
	Trigger   []triggerVector `json:"trigger"`
	SeqNewer  []seqVector     `json:"seqNewer"`
	State     []stateVector   `json:"state"`
	Invalid   []invalidVector `json:"invalid"`
	Pairing   pairingVector   `json:"pairing"`
	Handshake handshakeVector `json:"handshake"`
	Session   []sessionVector `json:"session"`
}

func errName(err error) string {
	switch err {
	case ErrShort:
		return "short"
	case ErrLong:
		return "long"
	case ErrMagic:
		return "magic"
	case ErrVersion:
		return "version"
	case ErrType:
		return "type"
	case ErrLength:
		return "length"
	case ErrReserved:
		return "reserved"
	case ErrRange:
		return "range"
	}
	return "ok"
}

// checkDatagram runs a datagram through header and body validation the way
// a receiver does before authentication.
func checkDatagram(b []byte) error {
	h, err := CheckHeader(b)
	if err != nil {
		return err
	}
	switch h.Type {
	case TypeState:
		_, _, err = DecodeState(b)
	case TypeHeartbeat:
		_, err = DecodeHeartbeat(b)
	case TypeDisconnect:
		_, err = DecodeDisconnect(b)
	case TypeRumble:
		_, err = DecodeRumble(b)
	case TypeHello:
		_, err = DecodeHello(b)
	case TypeWelcome:
		_, err = DecodeWelcome(b)
	case TypeReject:
		_, err = DecodeReject(b)
	case TypeDiscoverReply:
		_, err = DecodeDiscoverReply(b)
	}
	return err
}

func seqBytes(n int, seed byte) (b [NonceSize]byte) {
	for i := range b {
		b[i] = seed + byte(i*n)
	}
	return b
}

func buildVectors() vectorFile {
	v := vectorFile{
		Comment: "PocketPad protocol v1 test vectors. Generated by desktop/internal/protocol/vectors_test.go; do not edit by hand.",
		Version: Version,
	}
	for _, f := range []float32{0, 1, -1, 0.5, -0.5, 0.25, -0.25, 0.001, -0.001, 0.99999, 1.5, -1.5} {
		v.Axis = append(v.Axis, axisVector{f, EncodeAxis(f)})
	}
	for _, f := range []float32{0, 1, 0.5, 0.25, 0.75, 0.001, -0.5, 1.5} {
		v.Trigger = append(v.Trigger, triggerVector{f, EncodeTrigger(f)})
	}
	for _, p := range [][2]uint16{{1, 0}, {0, 1}, {5, 5}, {0, 65535}, {65535, 0}, {100, 65000}, {32767, 0}, {32768, 0}, {40000, 7232}, {7232, 40000}} {
		v.SeqNewer = append(v.SeqNewer, seqVector{p[0], p[1], SeqNewer(p[0], p[1])})
	}

	states := []struct {
		name string
		seq  uint16
		w    WireState
	}{
		{"neutral", 0, WireState{}},
		{"golden", 0x0102, goldenWire()},
		{"all buttons, snapshot", 65535, WireState{Buttons: ButtonsDefined, DPad: DPadUpLeft, Flags: FlagSnapshot, LeftX: -32768, LeftY: 1, RightX: -1, RightY: 12345, LeftTrigger: 1, RightTrigger: 254}},
		{"half sticks", 40000, (&ControllerState{LeftX: 0.5, LeftY: -0.5, RightX: -0.25, RightY: 0.25, LeftTrigger: 0.5, RightTrigger: 0.25, Buttons: ButtonLS | ButtonRS, DPad: DPadDown}).ToWire(0)},
	}
	for _, s := range states {
		var b [StateSize]byte
		PutState(b[:], s.seq, &s.w)
		v.State = append(v.State, stateVector{
			Name: s.name, Seq: s.seq, Buttons: uint16(s.w.Buttons), DPad: uint8(s.w.DPad), Flags: uint8(s.w.Flags),
			LX: s.w.LeftX, LY: s.w.LeftY, RX: s.w.RightX, RY: s.w.RightY, LT: s.w.LeftTrigger, RT: s.w.RightTrigger,
			Hex: hex.EncodeToString(b[:]),
		})
	}

	tagged := append(bytes.Clone(goldenState), make([]byte, TagSize)...)
	mod := func(b []byte, i int, x byte) []byte { b = bytes.Clone(b); b[i] = x; return b }
	invalid := []struct {
		name string
		b    []byte
	}{
		{"empty", nil},
		{"truncated header", tagged[:5]},
		{"bad magic", mod(tagged, 1, 'Q')},
		{"future version", mod(tagged, 2, 2)},
		{"unknown type", mod(tagged, 3, 0x7F)},
		{"untagged state", goldenState},
		{"state one byte long", append(bytes.Clone(tagged), 0)},
		{"reserved button bit", mod(tagged, 7, 0x80)},
		{"reserved flag bit", mod(tagged, 9, 0x80)},
		{"dpad out of range", mod(tagged, 8, 9)},
		{"oversized datagram", make([]byte, MaxDatagram+1)},
	}
	for _, c := range invalid {
		v.Invalid = append(v.Invalid, invalidVector{c.name, hex.EncodeToString(c.b), errName(checkDatagram(c.b))})
	}

	secret := mustHex("000102030405060708090a0b0c0d0e")
	pairKey := PairKey(secret)
	v.Pairing = pairingVector{hex.EncodeToString(secret), FormatPairingCode(secret), hex.EncodeToString(pairKey)}

	hello := Hello{DeviceID: 0x1122334455667788, ClientNonce: seqBytes(1, 0xA0), MinVersion: 1, MaxVersion: 1, Caps: CapRumble | CapBattery | CapLatencyEcho}
	hello.SetName("Test Phone")
	hb := make([]byte, HelloSize+HandshakeTagSize)
	PutHello(hb, &hello)
	copy(hb[HelloSize:], HandshakeTag(pairKey, hb[:HelloSize], nil))

	welcome := Welcome{SessionID: 0xCAFEBABE, ServerNonce: seqBytes(3, 0x10), Version: 1, Caps: CapRumble | CapLatencyEcho, HeartbeatMs: 500, TimeoutMs: 300, MaxRateHz: 250}
	wb := make([]byte, WelcomeSize+HandshakeTagSize)
	PutWelcome(wb, &welcome)
	copy(wb[WelcomeSize:], HandshakeTag(pairKey, wb[:WelcomeSize], hello.ClientNonce[:]))

	keys := DeriveSessionKeys(pairKey, hello.DeviceID, hello.ClientNonce, welcome.ServerNonce, welcome.SessionID)
	v.Handshake = handshakeVector{
		DeviceID: hello.DeviceID, DeviceName: hello.Name(),
		ClientNonceHex: hex.EncodeToString(hello.ClientNonce[:]), ServerNonceHex: hex.EncodeToString(welcome.ServerNonce[:]),
		SessionID: welcome.SessionID,
		HelloHex:  hex.EncodeToString(hb), WelcomeHex: hex.EncodeToString(wb),
		C2SKeyHex: hex.EncodeToString(keys.ClientToServer), S2CKeyHex: hex.EncodeToString(keys.ServerToClient),
	}

	c2s, s2c := NewSessionMAC(keys.ClientToServer), NewSessionMAC(keys.ServerToClient)
	seal := func(name, dir string, ext ExtSeq, put func(b []byte, seq uint16) int) {
		b := make([]byte, MaxDatagram)
		n := put(b, ext.Wire())
		m := c2s
		if dir == "s2c" {
			m = s2c
		}
		m.Seal(b, n, ext)
		v.Session = append(v.Session, sessionVector{name, dir, uint64(ext), hex.EncodeToString(b[:n+TagSize])})
	}
	gw := goldenWire()
	seal("state", "c2s", 0, func(b []byte, seq uint16) int { PutState(b, seq, &gw); return StateSize })
	seal("state after one wraparound", "c2s", 65536+0x0102, func(b []byte, seq uint16) int { PutState(b, seq, &gw); return StateSize })
	seal("heartbeat", "c2s", 1, func(b []byte, seq uint16) int {
		PutHeartbeat(b, seq, &Heartbeat{TimeUs: 123456789, RttUs: 2500, Battery: 64})
		return HeartbeatSize
	})
	seal("heartbeat echo", "s2c", 0, func(b []byte, seq uint16) int {
		PutHeartbeat(b, seq, &Heartbeat{TimeUs: 42, EchoUs: 123456789, Battery: BatteryUnknown})
		return HeartbeatSize
	})
	seal("rumble", "s2c", 1, func(b []byte, seq uint16) int {
		PutRumble(b, seq, &Rumble{Left: 0xFFFF, Right: 0x4000, DurationMs: 750})
		return RumbleSize
	})
	seal("disconnect", "c2s", 2, func(b []byte, seq uint16) int { PutDisconnect(b, seq, ReasonUser); return DisconnectSize })
	return v
}

func TestVectors(t *testing.T) {
	want := buildVectors()
	enc, err := json.MarshalIndent(want, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	enc = append(enc, '\n')
	if *update {
		if err := os.WriteFile(vectorsPath, enc, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(vectorsPath)
	if err != nil {
		t.Fatalf("%v (run with -update to create it)", err)
	}
	if !bytes.Equal(got, enc) {
		t.Fatalf("%s is out of date or the wire format changed; rerun with -update and review the diff", vectorsPath)
	}

	// Independently of generation, check the decoders and the handshake
	// against the file contents.
	var v vectorFile
	if err := json.Unmarshal(got, &v); err != nil {
		t.Fatal(err)
	}
	for _, s := range v.State {
		seq, w, err := DecodeState(mustHex(s.Hex))
		if err != nil || seq != s.Seq || uint16(w.Buttons) != s.Buttons || w.LeftX != s.LX || w.RightTrigger != s.RT {
			t.Errorf("state %q: %d %+v %v", s.Name, seq, w, err)
		}
	}
	for _, c := range v.Invalid {
		if got := errName(checkDatagram(mustHex(c.Hex))); got != c.Error || got == "ok" {
			t.Errorf("invalid %q: got %s, want %s", c.Name, got, c.Error)
		}
	}
	pk := mustHex(v.Pairing.PairKeyHex)
	if !VerifyHandshake(pk, mustHex(v.Handshake.HelloHex), nil) {
		t.Error("hello tag")
	}
	if !VerifyHandshake(pk, mustHex(v.Handshake.WelcomeHex), mustHex(v.Handshake.ClientNonceHex)) {
		t.Error("welcome tag")
	}
	for _, s := range v.Session {
		key := mustHex(v.Handshake.C2SKeyHex)
		if s.Direction == "s2c" {
			key = mustHex(v.Handshake.S2CKeyHex)
		}
		pkt := mustHex(s.Hex)
		if err := checkDatagram(pkt); err != nil {
			t.Errorf("session %q: %v", s.Name, err)
		}
		if !NewSessionMAC(key).Verify(pkt, ExtSeq(s.Ext)) {
			t.Errorf("session %q: tag", s.Name)
		}
	}
}
